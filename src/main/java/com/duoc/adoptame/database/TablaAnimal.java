package com.duoc.adoptame.database;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Crea las tablas perros y gatos si todavía no existen.
 */
public final class TablaAnimal {

    /** Código ORA-00955: el nombre ya lo usa otro objeto (la tabla ya existe). */
    private static final int ORA_TABLA_YA_EXISTE = 955;

    private static final String DDL_PERROS =
            "CREATE TABLE perros ("
                    + "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "nombre VARCHAR2(100) NOT NULL, "
                    + "anio NUMBER(4) NOT NULL, "
                    + "edad NUMBER(3) NOT NULL, "
                    + "raza VARCHAR2(100) NOT NULL, "
                    + "vacunas_al_dia NUMBER(1) NOT NULL, "
                    + "apto_ninos NUMBER(1) NOT NULL)";

    private static final String DDL_GATOS =
            "CREATE TABLE gatos ("
                    + "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "nombre VARCHAR2(100) NOT NULL, "
                    + "anio NUMBER(4) NOT NULL, "
                    + "edad NUMBER(3) NOT NULL, "
                    + "sociabilidad NUMBER NOT NULL)";

    private TablaAnimal() {
    }

    public static void inicializar() throws SQLException {
        try (Connection conn = ConexionDB.obtenerConexion();
             Statement stmt = conn.createStatement()) {
            crearSiNoExiste(stmt, DDL_PERROS);
            crearSiNoExiste(stmt, DDL_GATOS);
        }
    }

    private static void crearSiNoExiste(Statement stmt, String ddl) throws SQLException {
        try {
            stmt.execute(ddl);
        } catch (SQLException e) {
            if (e.getErrorCode() != ORA_TABLA_YA_EXISTE) {
                throw e;
            }
        }
    }
}
